"""Rasterize DejaVu fonts to compact 2-bit alpha glyphs for the SMKTRON UI.
Run with Pillow on a development computer. License: assets/fonts/DejaVu-LICENSE.txt.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
from font_pack import append_glyph
ROOT=Path(__file__).resolve().parents[1]
FONTS=[('SP_F7','DejaVuSans-Bold.ttf',7,126),('SP_F8','DejaVuSans.ttf',8,126),('SP_F10','DejaVuSans-Bold.ttf',10,95),('SP_F13','DejaVuSans-Bold.ttf',13,95),('SP_F17','DejaVuSans-Bold.ttf',17,95),('SP_F14','DejaVuSansMono.ttf',14,126)]
lines=['/* Generated by tools/gen_smktron_fonts.py; DejaVu / Bitstream Vera license. */','#pragma once','typedef struct { uint8_t h, last; const uint8_t *w; const uint16_t *off; const uint8_t *data; } sp_font_t;']
for name,file,size,last in FONTS:
 font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/'+file,size);h=size+4;data=[];widths=[];offsets=[]
 for code in range(32,last+1):
  ch=chr(code);w=math.ceil(font.getlength(ch));widths.append(w);glyph=[]
  im=Image.new('L',(w,h));ImageDraw.Draw(im).text((0,0),ch,font=font,fill=255)
  vals=[min(3,(v+42)//85) for v in im.getdata()]
  for at in range(0,len(vals),4):
   byte=0
   for j,v in enumerate(vals[at:at+4]):byte|=v<<(6-j*2)
   glyph.append(byte)
  offsets.append(append_glyph(data,glyph))
 for typ,post,arr in [('uint8_t','W',widths),('uint16_t','O',offsets),('uint8_t','D',data)]:
  lines.append(f'static const {typ} {name}_{post}[] = {{')
  for at in range(0,len(arr),24):lines.append(','.join(str(v) for v in arr[at:at+24])+',')
  lines.append('};')
 lines.append(f'static const sp_font_t {name} = {{{h},{last},{name}_W,{name}_O,{name}_D}};')
(ROOT/'firmware/gen/smktron_fonts.h').write_text('\n'.join(lines)+'\n')
